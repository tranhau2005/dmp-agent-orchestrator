from uuid import uuid4


class AOError(Exception):
    def __init__(self, message: str = "", *, correlation_id: str | None = None):
        super().__init__(message)
        self.error_code = type(self).__name__
        self.correlation_id = correlation_id or str(uuid4())


class SetupFailure(AOError): ...
class CapabilityError(AOError): ...
class ConfigurationError(AOError): ...
class GraphValidationError(AOError): ...
class IllegalTransitionError(AOError): ...
class ContractViolationError(AOError): ...
class ImmutabilityError(AOError): ...
class PolicyViolationError(AOError): ...
class ResultValidationError(AOError): ...
class AdapterFailure(AOError): ...
class ValidationGateFailure(AOError): ...
class ApprovalDenied(AOError): ...
class ClaimRejected(AOError): ...
class LimitExceeded(AOError): ...
class TimeoutExceeded(AOError): ...
class UncertainTransition(AOError): ...
